"""Give the vocab app (vocab/app/) the same colors and fonts as the rest of the site.

Runs automatically before each render (`pre-render` in _quarto.yml). Reads brand/_brand.yml
and writes vocab/app/brand.css, which sets the app's CSS variables (--accent, --text, ...)
and fonts. Change the brand once and the site, PDFs, slides and vocab app all follow.
Without brand.css the app still works, in its own default colors.

Writes:
    vocab/app/brand.css   (not saved in git)
"""

from pathlib import Path
from urllib.parse import quote_plus

import yaml

from genfile import write_if_changed

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "brand" / "_brand.yml"
OUT = ROOT / "vocab" / "app" / "brand.css"


def font_faces(fonts):
    """@font-face rules for fonts stored in the repo (`source: file` in _brand.yml). The site copies
    brand/fonts/ (resources in _quarto.yml), so from vocab/app/ they're at ../../brand/fonts/."""
    rules = []
    for f in fonts:
        for file in f.get("files", []) if f.get("source") == "file" else []:
            rules.append(f'@font-face {{ font-family: "{f["family"]}"; src: url("../../brand/{file["path"]}"); '
                         f'font-weight: {file.get("weight", 400)}; font-style: {file.get("style", "normal")}; font-display: swap; }}')
    return "\n".join(rules)


def google_fonts_url(fonts):
    """One Google Fonts link for every `source: google` font in _brand.yml."""
    families = []
    for f in fonts:
        if f.get("source") != "google":
            continue
        weights = f.get("weight", [400])
        weights = weights if isinstance(weights, list) else [weights]
        if "italic" in f.get("style", []):
            spec = "ital,wght@" + ";".join([f"0,{w}" for w in weights] + [f"1,{w}" for w in weights])
        else:
            spec = "wght@" + ";".join(str(w) for w in weights)
        families.append("family=" + quote_plus(f["family"]) + ":" + spec)
    return "https://fonts.googleapis.com/css2?" + "&".join(families) + "&display=swap"


def main():
    brand = yaml.safe_load(BRAND.read_text(encoding="utf-8"))
    color = brand["color"]
    palette = color["palette"]

    def c(name):
        """A color from _brand.yml: a palette name (navy) or a role (primary)."""
        value = color.get(name, name)
        return palette.get(value, value)

    typo = brand["typography"]
    body = typo["base"]["family"]
    head = typo["headings"]["family"]
    # Color emoji fonts first: Noto Sans SC has black-and-white copies of some emoji.
    zh = "\"Apple Color Emoji\", \"Segoe UI Emoji\", \"Noto Color Emoji\", \"Noto Sans SC\", \"PingFang SC\", \"Microsoft YaHei\""

    google = [f for f in typo["fonts"] if f.get("source") == "google"]
    css = f"""/* Generated by scripts/vocab_brand.py from brand/_brand.yml. Don't edit by hand. */
{f'@import url("{google_fonts_url(google)}");' if google else ""}
{font_faces(typo["fonts"])}

:root {{
  --bg: {palette.get("sky", "#f6f7f9")}; --panel: {c("background")}; --text: {c("foreground")};
  --accent: {c("primary")}; --accent-soft: {palette.get("sky", "#e6f0fa")};
  --stripe: {c("secondary")}; --ref-head: {c("primary")};
  --font-body: "{body}", {zh}, system-ui, sans-serif;
  --font-head: "{head}", "{body}", {zh}, system-ui, sans-serif;
}}
/* Dark mode: navy text is too dark on a dark background, so links and highlights use the logo blue. */
@media (prefers-color-scheme: dark) {{
  :root {{ --bg: #14171b; --panel: #1d2126; --text: #e8eaed;
          --accent: color-mix(in srgb, {c("secondary")} 70%, white); --accent-soft: #1f3347;
          --ref-head: {c("tertiary")}; }}
}}

body, header input[type=search] {{ font-family: var(--font-body); }}
header h1, main h2 {{ font-family: var(--font-head); color: var(--accent); }}
header {{ border-bottom: 3px solid var(--stripe); }}
"""
    if write_if_changed(OUT, css):
        print("vocab_brand.py: wrote vocab/app/brand.css")


if __name__ == "__main__":
    main()
